<?php

require_once 'config/database.php';
require_once 'auth/check.php';

require_login();

/*
|--------------------------------------------------------------------------
| التحقق من وجود اسم الملف
|--------------------------------------------------------------------------
*/

if (!isset($_GET['file']) || empty($_GET['file'])) {
    http_response_code(400);
    die('طلب غير صالح.');
}

/*
|--------------------------------------------------------------------------
| تنظيف اسم الملف
|--------------------------------------------------------------------------
*/

$filename = basename($_GET['file']);

/*
|--------------------------------------------------------------------------
| السماح بامتداد DOCX فقط
|--------------------------------------------------------------------------
*/

if (
    strtolower(pathinfo($filename, PATHINFO_EXTENSION)) !== 'docx'
) {
    http_response_code(403);
    die('نوع الملف غير مسموح.');
}

/*
|--------------------------------------------------------------------------
| منع أسماء غير طبيعية
|--------------------------------------------------------------------------
*/

if (
    $filename === '.' ||
    $filename === '..' ||
    !preg_match('/^[a-f0-9]{32}\.docx$/i', $filename)
) {
    http_response_code(403);
    die('اسم الملف غير صالح.');
}

/*
|--------------------------------------------------------------------------
| المسار الحقيقي
|--------------------------------------------------------------------------
*/

$filepath = __DIR__ . '/converted/' . $filename;

/*
|--------------------------------------------------------------------------
| التأكد من وجود الملف
|--------------------------------------------------------------------------
*/

if (!is_file($filepath) || !is_readable($filepath)) {
    http_response_code(404);
    die('الملف غير موجود.');
}

/*
|--------------------------------------------------------------------------
| الحصول على المستخدم الحالي
|--------------------------------------------------------------------------
*/

$userId = get_current_user_id();

/*
|--------------------------------------------------------------------------
| جلب العملية من قاعدة البيانات
|--------------------------------------------------------------------------
|
| نتحقق من:
|
| 1. اسم الملف
| 2. المستخدم الحالي
|
| حتى لا يستطيع مستخدم تحميل ملف مستخدم آخر.
|
*/

$stmt = $pdo->prepare("
    SELECT
        id,
        original_name,
        word_path,
        file_size,
        status
    FROM conversions
    WHERE user_id = ?
      AND word_path LIKE ?
      AND status = 'completed'
    LIMIT 1
");

$stmt->execute([
    $userId,
    '%' . $filename
]);

$conversion = $stmt->fetch(PDO::FETCH_ASSOC);

/*
|--------------------------------------------------------------------------
| الملف غير تابع للمستخدم
|--------------------------------------------------------------------------
*/

if (!$conversion) {
    http_response_code(403);
    die('ليس لديك صلاحية تحميل هذا الملف.');
}

/*
|--------------------------------------------------------------------------
| التأكد من أن المسار الموجود في قاعدة البيانات
| يشير فعلاً إلى الملف المطلوب
|--------------------------------------------------------------------------
*/

$dbFilename = basename($conversion['word_path']);

if (!hash_equals($dbFilename, $filename)) {
    http_response_code(403);
    die('الملف غير صالح.');
}

/*
|--------------------------------------------------------------------------
| اسم التحميل
|--------------------------------------------------------------------------
*/

$downloadName = $filename;

if (
    !empty($conversion['original_name'])
) {

    $originalName = pathinfo(
        $conversion['original_name'],
        PATHINFO_FILENAME
    );

    /*
    |--------------------------------------------------------------------------
    | منع أي محاولات تلاعب باسم الملف
    |--------------------------------------------------------------------------
    */

    $originalName = str_replace(
        [
            "\r",
            "\n",
            '/',
            '\\'
        ],
        '',
        $originalName
    );

    if ($originalName !== '') {

        $downloadName =
            $originalName . '.docx';
    }
}

/*
|--------------------------------------------------------------------------
| حجم الملف
|--------------------------------------------------------------------------
*/

$fileSize = filesize($filepath);

if ($fileSize === false) {
    http_response_code(500);
    die('تعذر قراءة حجم الملف.');
}

/*
|--------------------------------------------------------------------------
| تنظيف أي Output سابق
|--------------------------------------------------------------------------
|
| مهم جدًا حتى لا يتلف ملف DOCX.
|
*/

while (ob_get_level()) {
    ob_end_clean();
}

/*
|--------------------------------------------------------------------------
| Headers
|--------------------------------------------------------------------------
*/

header(
    'Content-Type: application/vnd.openxmlformats-officedocument.wordprocessingml.document'
);

header(
    'Content-Disposition: attachment; filename="' .
    basename($filename) .
    '"; filename*=UTF-8\'\'' .
    rawurlencode($downloadName)
);

header('Content-Transfer-Encoding: binary');

header('Accept-Ranges: bytes');

header('Content-Length: ' . $fileSize);

header('Cache-Control: private, no-store, no-cache, must-revalidate');

header('Pragma: no-cache');

header('Expires: 0');

/*
|--------------------------------------------------------------------------
| إرسال الملف
|--------------------------------------------------------------------------
*/

$handle = fopen($filepath, 'rb');

if ($handle === false) {
    http_response_code(500);
    die('تعذر فتح الملف.');
}

while (!feof($handle)) {

    echo fread($handle, 1024 * 1024);

    flush();
}

fclose($handle);

exit;
?>